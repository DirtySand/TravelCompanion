#!/usr/bin/env python3
"""TravelCompanion encrypted log tool.

  keygen   create the recipient key pair; writes the private key file and
           the firmware header with the public key (log_pubkey.h)
  decrypt  decrypt one or more .TCL files from the SD card to CSV
           (waypoint lines "#WP,..." go to <output>_waypoints.csv when -o
           is given, otherwise they are printed with the rest)

File format: see log_crypto.h in the firmware.
Requires PyNaCl:  python3 -m pip install pynacl
"""

import argparse
import hashlib
import os
import struct
import sys

try:
    from nacl import bindings
except ImportError:
    sys.exit("PyNaCl is missing: python3 -m pip install pynacl")

MAGIC = b"TCLOGv01"
HEADER_SIZE = 64
KEY_SIZE = 32
MAC_SIZE = 16
NONCE_PREFIX = slice(40, 56)
EPHEMERAL = slice(8, 40)


def keygen(args):
    if os.path.exists(args.private_key) and not args.force:
        sys.exit(f"{args.private_key} already exists (use --force to replace it; "
                 "old logs can then no longer be decrypted)")
    secret = os.urandom(KEY_SIZE)
    public = bindings.crypto_scalarmult_base(secret)

    fd = os.open(args.private_key, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(secret.hex() + "\n")

    body = ", ".join(f"0x{b:02X}" for b in public)
    with open(args.header, "w") as f:
        f.write("#ifndef LOG_PUBKEY_H\n#define LOG_PUBKEY_H\n\n")
        f.write("// Generated by tools/tclog.py keygen. Public key only.\n")
        f.write("#include <stdint.h>\n\n")
        f.write("static const uint8_t LOG_RECIPIENT_PUBLIC_KEY[32] = {\n")
        f.write(f"    {body}}};\n\n#endif // LOG_PUBKEY_H\n")
    print(f"private key: {args.private_key}  (keep it OFF the device and out of git)")
    print(f"public key header: {args.header}")


def load_secret(path):
    with open(path) as f:
        secret = bytes.fromhex(f.read().strip())
    if len(secret) != KEY_SIZE:
        sys.exit(f"{path}: expected {KEY_SIZE} bytes of hex")
    return secret


WAYPOINT_PREFIX = "#WP,"
WAYPOINT_HEADER = "id,utc,lat,lon,alt_m,east_m,north_m,track_m,session\n"


class LineRouter:
    """Splits the decrypted text into lines; waypoint lines go elsewhere."""

    def __init__(self, out, waypoints):
        self.out = out
        self.waypoints = waypoints
        self.pending = ""

    def write(self, text):
        self.pending += text
        while "\n" in self.pending:
            line, self.pending = self.pending.split("\n", 1)
            self._route(line + "\n")

    def _route(self, line):
        if self.waypoints is not None and line.startswith(WAYPOINT_PREFIX):
            self.waypoints.write(line[len(WAYPOINT_PREFIX):])
        else:
            self.out.write(line)

    def close(self):
        if self.pending:
            self._route(self.pending)
            self.pending = ""


def decrypt_file(path, secret, out):
    with open(path, "rb") as f:
        data = f.read()
    header = data[:HEADER_SIZE]
    if len(header) < HEADER_SIZE or header[:8] != MAGIC:
        print(f"{path}: not a TravelCompanion log", file=sys.stderr)
        return False

    ephemeral = header[EPHEMERAL]
    shared = bindings.crypto_scalarmult(secret, ephemeral)
    public = bindings.crypto_scalarmult_base(secret)
    key = hashlib.blake2b(shared + ephemeral + public, digest_size=32).digest()
    prefix = header[NONCE_PREFIX]

    offset = HEADER_SIZE
    index = 0
    ok = True
    while offset < len(data):
        if offset + 2 + MAC_SIZE > len(data):
            print(f"{path}: truncated record #{index} ignored", file=sys.stderr)
            break
        (length,) = struct.unpack_from("<H", data, offset)
        mac = data[offset + 2:offset + 2 + MAC_SIZE]
        start = offset + 2 + MAC_SIZE
        cipher = data[start:start + length]
        if len(cipher) < length:
            print(f"{path}: truncated record #{index} ignored", file=sys.stderr)
            break
        nonce = prefix + struct.pack("<Q", index)
        try:
            plain = bindings.crypto_aead_xchacha20poly1305_ietf_decrypt(
                cipher + mac, header, nonce, key)
        except Exception:
            print(f"{path}: record #{index} failed authentication "
                  "(wrong key or damaged file)", file=sys.stderr)
            ok = False
            break
        out.write(plain.decode("ascii", errors="replace"))
        offset = start + length
        index += 1
    return ok


def decrypt(args):
    secret = load_secret(args.private_key)
    out = open(args.output, "w", newline="") if args.output else sys.stdout
    waypoints = None
    if args.output:
        stem, _ = os.path.splitext(args.output)
        waypoints = open(stem + "_waypoints.csv", "w", newline="")
        waypoints.write(WAYPOINT_HEADER)
    router = LineRouter(out, waypoints)
    ok = True
    try:
        for path in args.files:
            ok = decrypt_file(path, secret, router) and ok
        router.close()
    finally:
        if args.output:
            out.close()
            waypoints.close()
    sys.exit(0 if ok else 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    k = sub.add_parser("keygen", help="create the key pair")
    k.add_argument("--private-key", default="tclog_private.key")
    k.add_argument("--header", default="log_pubkey.h")
    k.add_argument("--force", action="store_true")
    k.set_defaults(func=keygen)

    d = sub.add_parser("decrypt", help="decrypt .TCL files to CSV")
    d.add_argument("files", nargs="+")
    d.add_argument("--private-key", default="tclog_private.key")
    d.add_argument("-o", "--output")
    d.set_defaults(func=decrypt)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
